#pragma once

//==========================================================
// OutlineConst.h
// 原神式アウトライン（背面押し出し）の見た目パラメータ
//==========================================================
namespace OutlineConst
{
	// 太さ：ワールド単位の押し出し量。
	// 近いほど太く・遠いほど細く見える（自然な輪郭）。
	// 大きいほど線が太い（0.02〜0.06 くらいが目安）。
	constexpr float Width        = 0.07f;   // キャラ・アイテム（小さめオブジェクト）
	// Box惑星・床・WindBox等は大きいので、同じ幅だと相対的に細く見える。
	// 大きいオブジェクト用に太めにして見た目の太さを揃える。
	constexpr float TerrainWidth = 0.18f;   // Box惑星・床・WindBox・SpikeBox（大きいオブジェクト）

	// 輪郭色の暗さ係数（ベース色×この値）。0=真っ黒、1=元色のまま。
	// 0.15 前後で「元色を暗くした自然な輪郭」になる（原神風）。
	constexpr float ColorMul = 0.15f;
}
